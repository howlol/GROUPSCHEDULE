"""
Скрипт инициализации и заполнения базы данных SQLite (schedule.db).

Создаёт таблицы users и schedule (если их ещё нет) и заполняет таблицу
schedule тестовыми данными для двух учебных групп.

Выполняется локально один раз перед запуском приложения:

    python database.py
"""

import os
import sqlite3

# Путь к файлу БД (рядом со скриптом)
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DB_PATH = os.path.join(BASE_DIR, "schedule.db")


def get_connection():
    """Возвращает подключение к SQLite с доступом к строкам по имени столбца."""
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    """Создаёт таблицы users и schedule при их отсутствии (п. 3.1 ТЗ)."""
    conn = get_connection()
    try:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS users (
                id            INTEGER PRIMARY KEY AUTOINCREMENT,
                username      TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                group_name    TEXT NOT NULL
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS schedule (
                id            INTEGER PRIMARY KEY AUTOINCREMENT,
                group_name    TEXT NOT NULL,
                weekday       TEXT NOT NULL,
                lesson_number INTEGER NOT NULL,
                time_start    TEXT NOT NULL,
                time_end      TEXT NOT NULL,
                subject       TEXT NOT NULL,
                teacher       TEXT NOT NULL,
                room          TEXT NOT NULL
            )
            """
        )
        conn.commit()
    finally:
        conn.close()


