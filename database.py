def fill_test_data():
    """Заполняет таблицу schedule тестовыми данными для 1–2 групп (п. 3.2 ТЗ)."""
    conn = get_connection()
    try:
        count = conn.execute("SELECT COUNT(*) FROM schedule").fetchone()[0]
        if count:
            print(f"Таблица schedule уже содержит {count} записей — "
                  "заполнение пропущено.")
            return
        conn.executemany(
            """
            INSERT INTO schedule
                (group_name, weekday, lesson_number, time_start, time_end,
                 subject, teacher, room)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            """,
            TEST_SCHEDULE,
        )
        conn.commit()
        print(f"В таблицу schedule добавлено записей: {len(TEST_SCHEDULE)}")
    finally:
        conn.close()


